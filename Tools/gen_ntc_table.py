"""
NTC温度查表生成器
参数: B=3950, R0=10k, R_Balance=10k
接线: [GND] --- [10k] --- ADC_In --- [NTC] --- [+5V]
ADC: 10-bit (0-1023), 参考电压=Vcc(自动抵消)
输出: 1024点 int16_t 数组, 温度值 = °C × 100

用法: python gen_ntc_table.py
"""

import math

# ====== NTC参数 ======
B = 3950.0          # B值
T0 = 298.15         # 25°C 开尔文
R0 = 10000.0        # 标称电阻 @25°C
R_BALANCE = 10000.0 # 分压平衡电阻
TEMP_MIN = -20.0    # 最小温度 °C
TEMP_MAX = 150.0    # 最大温度 °C

def adc_to_temp_celsius(adc: int) -> float:
    """将ADC原始值(0-1023)转换为温度(°C)"""
    if adc <= 0:
        return TEMP_MIN
    R = R_BALANCE * (1024.0 / adc - 1.0)
    T_k = 1.0 / (1.0 / T0 + (1.0 / B) * math.log(R / R0))
    return T_k - 273.15

# ====== 生成1024点表 ======
table = []
for adc in range(1024):
    temp = adc_to_temp_celsius(adc)
    temp = max(TEMP_MIN, min(TEMP_MAX, temp))
    table.append(int(round(temp * 100)))

# ====== 输出为C文件 ======
output = []
output.append("// SPDX-License-Identifier: GPL-3.0-or-later")
output.append("// Auto-generated by gen_ntc_table.py — DO NOT EDIT")
output.append(f"// B={B}, R0={R0}, R_Balance={R_BALANCE}")
output.append("// Wiring: [GND] --- [10k] --- ADC_In --- [NTC] --- [+5V]")
output.append(f"// Temperature range: {TEMP_MIN}C ~ {TEMP_MAX}C, resolution 0.01C")
output.append("//")
output.append("// Usage: extern code int ntc_temp_table[1024];")
output.append("//        temp_celsius_x100 = ntc_temp_table[ADC_Convert(ch)];")
output.append("")
output.append("#define NTC_TABLE_SIZE 1024")
output.append("")
output.append("code int ntc_temp_table[NTC_TABLE_SIZE] = {")

for i in range(0, 1024, 10):
    row = ", ".join(f"{table[i + j]:5d}" for j in range(min(10, 1024 - i)))
    output.append(f"    {row},   // ADC {i:3d}~{min(i+9, 1023):3d}")

output.append("};")
output.append("")

with open("ntc_lut.c", "w", encoding="utf-8") as f:
    f.write("\n".join(output))

# ====== 控制台输出验证 ======
print("✅ ntc_lut.c 已生成")
print()
print(f"温度范围: [{TEMP_MIN}C, {TEMP_MAX}C]")
print(f"表大小: {len(table)} 点")
print()

# 单调性检查
ok = all(table[i] >= table[i-1] for i in range(1, 1024))
print(f"单调性检查: {'通过' if ok else '失败 !!!'}")
print()

# 关键点输出
print("关键参考点:")
print(f"  ADC   0 -> {table[0]//100}.{abs(table[0])%100:02d}C  (超量程下限)")
print(f"  ADC  89 -> {table[89]//100}.{abs(table[89])%100:02d}C  (约-20C)")
print(f"  ADC 512 -> {table[512]//100}.{abs(table[512])%100:02d}C  (中点)")
print(f"  ADC 1004 -> {table[1004]//100}.{abs(table[1004])%100:02d}C  (约150C)")
print(f"  ADC 1023 -> {table[1023]//100}.{abs(table[1023])%100:02d}C  (超量程上限)")
